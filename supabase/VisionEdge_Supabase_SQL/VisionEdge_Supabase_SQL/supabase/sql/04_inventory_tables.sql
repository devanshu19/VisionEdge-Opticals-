-- Catalog and inventory. Existing models store brand/category as text on products;
-- Brand and Category remain separate compatibility tables without inferred foreign keys.
CREATE TABLE IF NOT EXISTS public.brand (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS public.category (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS public.supplier (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL, phone VARCHAR(20), email VARCHAR(120),
    address TEXT, created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.frame (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    frame_code VARCHAR(50) UNIQUE, brand VARCHAR(100), model VARCHAR(100),
    name VARCHAR(150), category VARCHAR(50), shape VARCHAR(50), color VARCHAR(50),
    size VARCHAR(50), material VARCHAR(50), gender VARCHAR(20),
    price NUMERIC(12,2) NOT NULL, selling_price NUMERIC(12,2),
    stock INTEGER DEFAULT 0, min_stock INTEGER DEFAULT 5,
    image TEXT, vto_image TEXT, status VARCHAR(50) DEFAULT 'Available',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT frame_stock_nonnegative CHECK (stock IS NULL OR stock >= 0),
    CONSTRAINT frame_min_stock_nonnegative CHECK (min_stock IS NULL OR min_stock >= 0)
);
CREATE TABLE IF NOT EXISTS public.lens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lens_code VARCHAR(50) UNIQUE, name VARCHAR(150), brand VARCHAR(100),
    category VARCHAR(50) DEFAULT 'Contact & Optical Lenses',
    type VARCHAR(50), lens_type VARCHAR(50), coating VARCHAR(100),
    price NUMERIC(12,2) NOT NULL, selling_price NUMERIC(12,2),
    stock INTEGER DEFAULT 0, min_stock INTEGER DEFAULT 10, image TEXT,
    status VARCHAR(50) DEFAULT 'Available',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT lens_stock_nonnegative CHECK (stock IS NULL OR stock >= 0),
    CONSTRAINT lens_min_stock_nonnegative CHECK (min_stock IS NULL OR min_stock >= 0)
);
CREATE TABLE IF NOT EXISTS public.inventory_transaction (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type VARCHAR(50), product_id INTEGER,
    transaction_type VARCHAR(50), quantity INTEGER, notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
