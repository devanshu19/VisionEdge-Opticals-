-- Core identity and customer tables. Integer IDs are retained for Flask compatibility.
CREATE TABLE IF NOT EXISTS public."user" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    first_name VARCHAR(50), last_name VARCHAR(50),
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(120) UNIQUE, phone VARCHAR(20), gender VARCHAR(20),
    date_of_birth DATE, address TEXT,
    role VARCHAR(50) DEFAULT 'customer',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.customer (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(20) UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    gender VARCHAR(20), date_of_birth DATE, age INTEGER,
    phone VARCHAR(20) NOT NULL,
    alternate_phone VARCHAR(20), email VARCHAR(120),
    address TEXT, city VARCHAR(100), state VARCHAR(100), pincode VARCHAR(20),
    occupation VARCHAR(100), photo VARCHAR(255),
    status VARCHAR(20) DEFAULT 'Active',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by INTEGER
);

CREATE TABLE IF NOT EXISTS public.customer_profile (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL UNIQUE,
    blood_group VARCHAR(10), eye_conditions TEXT, allergies TEXT, notes TEXT
);
