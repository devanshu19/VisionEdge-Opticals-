-- Appointment, eye-test, and prescription tables.
CREATE TABLE IF NOT EXISTS public.appointment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    appointment_date DATE NOT NULL,
    appointment_time TIME WITHOUT TIME ZONE NOT NULL,
    appointment_type VARCHAR(50), doctor_name VARCHAR(100),
    status VARCHAR(50) DEFAULT 'Pending', notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.eye_test (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    appointment_id INTEGER,
    right_sphere VARCHAR(20), right_cylinder VARCHAR(20), right_axis VARCHAR(20),
    left_sphere VARCHAR(20), left_cylinder VARCHAR(20), left_axis VARCHAR(20),
    pd_value VARCHAR(20), remarks TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.prescription (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_number VARCHAR(50) UNIQUE,
    customer_id INTEGER NOT NULL,
    eye_test_id INTEGER,
    add_power VARCHAR(20), prescription_image VARCHAR(255),
    ai_extracted_text TEXT, confidence_score DOUBLE PRECISION,
    doctor_name VARCHAR(100),
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    date DATE DEFAULT CURRENT_DATE,
    expiry_date DATE, status VARCHAR(20) DEFAULT 'Completed'
);
