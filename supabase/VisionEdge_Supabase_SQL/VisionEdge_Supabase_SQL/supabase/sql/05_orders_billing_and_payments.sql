-- Orders, order items, billing, and payment records.
-- "order" is a PostgreSQL keyword; quote it wherever used as an identifier.
CREATE TABLE IF NOT EXISTS public."order" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(50) UNIQUE, order_number VARCHAR(50) UNIQUE,
    customer_id INTEGER NOT NULL, prescription_id INTEGER,
    status VARCHAR(50) DEFAULT 'Pending',
    total_amount NUMERIC(12,2) DEFAULT 0.00,
    order_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.order_item (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL,
    product_type VARCHAR(50), item_type VARCHAR(50),
    product_id INTEGER, item_id INTEGER,
    quantity INTEGER DEFAULT 1,
    price NUMERIC(12,2), total_price NUMERIC(12,2),
    CONSTRAINT order_item_quantity_positive CHECK (quantity IS NULL OR quantity > 0)
);
CREATE TABLE IF NOT EXISTS public.billing (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(50) NOT NULL UNIQUE,
    order_id INTEGER NOT NULL UNIQUE,
    subtotal NUMERIC(12,2) DEFAULT 0.00,
    discount NUMERIC(12,2) DEFAULT 0.00,
    gst NUMERIC(12,2) DEFAULT 0.00,
    total_amount NUMERIC(12,2) NOT NULL,
    payment_status VARCHAR(20) DEFAULT 'Pending', payment_method VARCHAR(50),
    invoice_pdf VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT billing_amounts_nonnegative CHECK (subtotal >= 0 AND discount >= 0 AND gst >= 0 AND total_amount >= 0)
);
CREATE TABLE IF NOT EXISTS public.payment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billing_id INTEGER NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    transaction_id VARCHAR(100), payment_method VARCHAR(50),
    payment_date TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payment_amount_nonnegative CHECK (amount >= 0)
);
CREATE TABLE IF NOT EXISTS public.order_status_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL, status VARCHAR(50), notes TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
