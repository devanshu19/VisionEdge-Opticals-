-- AI recommendations and virtual try-on history. Image columns store paths/URLs,
-- not binary file content. Keep the existing TEXT recommendation representation.
CREATE TABLE IF NOT EXISTS public.lens_recommendation (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER, prescription_id INTEGER,
    recommended_lens TEXT, reason TEXT, ai_response TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.frame_recommendation (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    face_shape VARCHAR(50), face_image VARCHAR(255),
    recommended_frames TEXT, selected_frame VARCHAR(100), ai_reason TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.virtual_try_on_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL, frame_id INTEGER NOT NULL,
    original_image VARCHAR(255), generated_image VARCHAR(255), tryon_image VARCHAR(255),
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.chat_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER, customer_id INTEGER,
    question TEXT NOT NULL, answer TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
