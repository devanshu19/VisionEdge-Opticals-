    ('user'), ('customer'), ('customer_profile'), ('appointment'), ('eye_test'),
    ('prescription'), ('brand'), ('category'), ('supplier'), ('frame'),
    ('lens'), ('inventory_transaction'), ('order'), ('order_item'), ('billing'),
    ('payment'), ('order_status_history'), ('lens_recommendation'),
    ('frame_recommendation'), ('virtual_try_on_history'), ('chat_history'),
    ('notification'), ('audit_log')
) AS expected(table_name)
